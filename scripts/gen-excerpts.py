#!/usr/bin/env python3
"""Generate website/excerpts.js from the real source files.

The "Open source" section of the website shows short excerpts of the Rust
workspace. They are generated, not typed, so they cannot drift from the code
by accident. Re-run this script after changing the referenced files:

    python3 scripts/gen-excerpts.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# key, file, first line, last line, substrings that mark highlighted lines
EXCERPTS = [
    ("privacy", "crates/vi-core/src/types.rs", 98, 122,
     ["/// 100% local processing", "#[default]", "MaxPrivacyOffline,", "pub fn allows_network",
      "!matches!(self, ProcessingProfile::MaxPrivacyOffline)"]),
    ("config", "crates/vi-core/src/config.rs", 9, 30,
     ["/// Never write temporary WAV", "pub ram_only_audio", "ram_only_audio: true", "block_password_fields: true"]),
    ("pin", "crates/vi-asr/src/catalog.rs", 20, 49,
     ["expected_sha256", "approx_download_mb", "license: \"CC-BY-4.0\""]),
    ("tree", "Cargo.toml", 1, 17,
     ["members", "license ="]),
]

RUST = re.compile(
    r"(?P<c>//.*)"
    r"|(?P<s>\"(?:[^\"\\]|\\.)*\")"
    r"|(?P<a>#\[[^\]]*\])"
    r"|(?P<n>\b\d[\d_.]*\b)"
    r"|(?P<k>\b(?:pub|fn|struct|enum|impl|const|static|let|match|self|Self|for|in|use|mod|true|false|bool|u32|u64|usize|str|String|Option|Result)\b)"
    r"|(?P<t>\b[A-Z][A-Za-z0-9_]*\b)"
    r"|(?P<f>\b[a-z_][a-z0-9_]*(?=\())"
)
TOML = re.compile(
    r"(?P<c>#.*)"
    r"|(?P<s>\"(?:[^\"\\]|\\.)*\")"
    r"|(?P<t>^\[[^\]]*\])"
    r"|(?P<f>^[A-Za-z_][A-Za-z0-9_.-]*(?=\s*=))"
    r"|(?P<k>\b(?:true|false)\b)"
    r"|(?P<n>\b\d[\d_.]*\b)"
)


def highlight(line: str, rx: re.Pattern) -> str:
    out, pos = [], 0
    for m in rx.finditer(line):
        out.append(html.escape(line[pos:m.start()], quote=False))
        kind = m.lastgroup
        out.append(f'<span class="sx-{kind}">{html.escape(m.group(0), quote=False)}</span>')
        pos = m.end()
    out.append(html.escape(line[pos:], quote=False))
    return "".join(out) or " "


def main() -> None:
    data = {}
    for key, rel, a, b, marks in EXCERPTS:
        src = (ROOT / rel).read_text(encoding="utf-8").splitlines()
        chunk = src[a - 1:b]
        rx = TOML if rel.endswith(".toml") else RUST
        hl = [i for i, ln in enumerate(chunk) if any(m in ln for m in marks)]
        data[key] = {
            "path": rel,
            "start": a,
            "lines": [highlight(ln, rx) for ln in chunk],
            "hl": hl,
        }
    out = ROOT / "website" / "excerpts.js"
    out.write_text(
        "/* Generated by scripts/gen-excerpts.py from the real source files. Do not edit by hand. */\n"
        "window.KR_CODE=" + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)} ({sum(len(v['lines']) for v in data.values())} lines)")


if __name__ == "__main__":
    main()
