"""Generate crates/vi-win32/src/icon_data.rs from assets/keyreed-icon.png.

Crops transparent padding, centres the mark in a square, downsamples with a
high-quality Lanczos filter to 64x64, and emits premultiplied BGRA (0xAARRGGBB)
so the floating listener and tray can box-filter it to any DPI-specific size.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "keyreed-icon.png"
OUT = ROOT / "crates" / "vi-win32" / "src" / "icon_data.rs"
N = 64

im = Image.open(SRC).convert("RGBA")
im = im.crop(im.getbbox())
side = max(im.size)
sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
sq = sq.resize((N, N), Image.LANCZOS)

vals = []
for r, g, b, a in sq.getdata():
    pr, pg, pb = (r * a + 127) // 255, (g * a + 127) // 255, (b * a + 127) // 255
    vals.append(f"0x{a:02X}{pr:02X}{pg:02X}{pb:02X}")

lines = [", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
OUT.write_text(
    "//! Generated by scripts/gen-icon-data.py from assets/keyreed-icon.png. Do not edit.\n"
    f"pub const KEYREED_ICON_SIZE: usize = {N};\n"
    f"/// {N}x{N} premultiplied BGRA (0xAARRGGBB), padding cropped, mark centred.\n"
    f"pub static KEYREED_ICON_64: [u32; {N * N}] = [\n    "
    + ",\n    ".join(lines)
    + ",\n];\n",
    encoding="utf-8",
)
print(f"wrote {OUT} ({N}x{N}, crop={im.size})")
